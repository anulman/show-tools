import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { relative } from 'node:path';

const [input = fileURLToPath(new URL('../lib/sampler/include/sample_engine.h', import.meta.url)),
  output = fileURLToPath(new URL('../lib/sampler/wasm-abi.ts', import.meta.url)), prefix = 'ST', ...extra] = process.argv.slice(2);
if (extra.length || !/^[A-Z]+$/.test(prefix)) throw new Error('Usage: generate-sampler-abi.ts [header] [output] [prefix]');
const source = (await readFile(input, 'utf8')).replace(/\/\*[\s\S]*?\*\/|\/\/[^\n]*/g, '');
const enums = [...source.matchAll(/\benum\b([^{;]*)\{([^{}]*)\}\s*;/g)];
if (!enums.length || enums.length !== (source.match(/\benum\b/g) || []).length) {
  throw new Error('Unsupported sampler enum declaration.');
}
const constants = new Map<string, number>();
for (const [, name, body] of enums) {
  if (!/^\s*(?:[A-Za-z_]\w*)?\s*$/.test(name)) throw new Error(`Unsupported enum name: ${name.trim()}`);
  let next = 0;
  const entries = body.trim().replace(/,\s*$/, '').split(',');
  for (const entry of entries) {
    const declaration = new RegExp(`^\\s*${prefix}_([A-Z][A-Z0-9_]*)(?:\\s*=\\s*([+-]?(?:0[xX][0-9a-fA-F]+|0[bB][01]+|0[0-7]*|[1-9][0-9]*)))?\\s*$`).exec(entry);
    if (!declaration) throw new Error(`Unsupported sampler enum value: ${entry.trim()}`);
    const [, key, literal] = declaration;
    if (constants.has(key)) throw new Error(`Duplicate sampler enum value: ST_${key}`);
    if (literal !== undefined) {
      const sign = literal.startsWith('-') ? -1 : 1;
      const unsigned = literal.replace(/^[+-]/, '');
      const base = unsigned.length > 1 && /^0[0-7]+$/.test(unsigned) ? `0o${unsigned.slice(1)}` : unsigned;
      next = sign * Number(BigInt(base));
    }
    if (!Number.isSafeInteger(next)) throw new Error(`Sampler enum value is not a safe integer: ST_${key}`);
    constants.set(key, next++);
  }
}
const sourcePath = relative(fileURLToPath(new URL('../', import.meta.url)), input).replaceAll('\\', '/');
const generated = `// Generated by scripts/generate-sampler-abi.ts from ${sourcePath}.\nexport const ${prefix} = Object.freeze({\n${[...constants].map(([key, value]) => `  ${key}: ${value},`).join('\n')}\n});\n`;
let previous = '';
try { previous = await readFile(output, 'utf8'); }
catch (error) {
  if (!(typeof error === 'object' && error !== null && 'code' in error && error.code === 'ENOENT')) throw error;
}
if (previous !== generated) await writeFile(output, generated);
